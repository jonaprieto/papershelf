import XCTest
import PDFKit
import AppKit
@testable import PaperShelfCore
@testable import PaperShelf

@MainActor
final class NoteSidecarTests: XCTestCase {

    func testAnnotationsWriteAndOverwriteTheSiblingSidecar() async throws {
        let folder = FileManager.default.temporaryDirectory
            .appendingPathComponent("sidecar-\(UUID().uuidString)")
        try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: folder) }

        let pdf = folder.appendingPathComponent("paper.pdf")
        try makeTextPDF(at: pdf, text: "alpha")
        let view = PDFView()
        view.document = try XCTUnwrap(PDFDocument(url: pdf))
        let annotator = Annotator()
        let prefs = Prefs.shared
        let oldSync = prefs.syncNotesSidecar
        defer { prefs.syncNotesSidecar = oldSync }
        prefs.syncNotesSidecar = true
        annotator.attach(view, url: pdf)
        let style = Palette.shared.styles[0]
        let scope = HighlightMeaningScope.forDocument(pdf, id: "sidecar-document")
        defer { Palette.shared.resetMeanings(in: scope) }
        Palette.shared.setMeaning("Delete", on: style, scope: scope)
        annotator.setDocumentID("sidecar-document")
        view.currentSelection = try XCTUnwrap(view.document?.findString("alpha", withOptions: []).first)

        XCTAssertEqual(annotator.highlightSelection(colour: style.nsColor, note: "keep"), 1)
        annotator.flush()
        let sidecar = notesSidecarURL(for: pdf)
        let first = try await waitForText(at: sidecar, containing: "keep")
        XCTAssertTrue(first.contains("Generated by PaperShelf"))
        XCTAssertTrue(first.contains("Colour: `#"))
        XCTAssertTrue(first.contains("*Delete*"), first)
        XCTAssertTrue(first.contains("Marked "))
        XCTAssertTrue(annotator.notesSidecarIsCurrent)

        let mark = try XCTUnwrap(annotator.marks.first)
        prefs.syncNotesSidecar = false
        annotator.setNote("do not rewrite", on: mark)
        annotator.flush()
        try await Task.sleep(for: .milliseconds(100))
        XCTAssertEqual(try String(contentsOf: sidecar), first)
    }

    func testACompletedRenameMovesTheExistingSidecar() throws {
        let folder = FileManager.default.temporaryDirectory
            .appendingPathComponent("sidecar-move-\(UUID().uuidString)")
        try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: folder) }

        let oldPDF = folder.appendingPathComponent("old.pdf")
        let newPDF = folder.appendingPathComponent("new.pdf")
        let oldSidecar = notesSidecarURL(for: oldPDF)
        try Data("managed".utf8).write(to: oldSidecar)
        let item = PaperShelfCore.Item(root: folder, source: oldPDF, destination: newPDF,
                                       status: .renamed, carriedOut: true)

        moveNotesSidecar(for: item)

        XCTAssertFalse(FileManager.default.fileExists(atPath: oldSidecar.path))
        XCTAssertEqual(try String(contentsOf: notesSidecarURL(for: newPDF)), "managed")
    }

    func testSidecarCanBeSyncedWithoutChangingThePDF() async throws {
        let folder = FileManager.default.temporaryDirectory
            .appendingPathComponent("sidecar-sync-\(UUID().uuidString)")
        try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: folder) }

        let pdf = folder.appendingPathComponent("paper.pdf")
        try makeTextPDF(at: pdf, text: "alpha")
        let prefs = Prefs.shared
        let oldSync = prefs.syncNotesSidecar
        defer { prefs.syncNotesSidecar = oldSync }
        prefs.syncNotesSidecar = true

        let view = PDFView()
        view.document = try XCTUnwrap(PDFDocument(url: pdf))
        let annotator = Annotator()
        annotator.attach(view, url: pdf)
        annotator.syncNotesSidecar()

        let sidecar = notesSidecarURL(for: pdf)
        let text = try await waitForText(at: sidecar, containing: "Generated by PaperShelf")
        XCTAssertTrue(text.contains("`\(pdf.path)`"))
        XCTAssertTrue(annotator.notesSidecarIsCurrent)
    }

    /// A paper with a highlight and a note made in another app, and no notes file yet.
    private func paperMarkedElsewhere() throws -> (folder: URL, pdf: URL) {
        let folder = FileManager.default.temporaryDirectory
            .appendingPathComponent("sidecar-foreign-\(UUID().uuidString)")
        try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        let pdf = folder.appendingPathComponent("paper.pdf")
        try makeTextPDF(at: pdf, text: "alpha")
        let document = try XCTUnwrap(PDFDocument(url: pdf))
        let page = try XCTUnwrap(document.page(at: 0))
        let hit = try XCTUnwrap(document.findString("alpha", withOptions: []).first)
        let mark = PDFAnnotation(bounds: hit.bounds(for: page), forType: .highlight, withProperties: nil)
        mark.contents = "from Preview"
        page.addAnnotation(mark)
        XCTAssertTrue(document.write(to: pdf))
        return (folder, pdf)
    }

    private func attach(_ annotator: Annotator, to pdf: URL) throws -> PDFView {
        let view = PDFView()
        view.document = try XCTUnwrap(PDFDocument(url: pdf))
        annotator.attach(view, url: pdf)
        return view
    }

    /// Marks made in another app used to reach the notes file only once something was
    /// marked here or Sync was pressed. A paper opened to read now gets the file as soon
    /// as its marks are read.
    func testMarksMadeElsewhereReachTheNotesFileOfAPaperOpenedToRead() async throws {
        let (folder, pdf) = try paperMarkedElsewhere()
        defer { try? FileManager.default.removeItem(at: folder) }
        let prefs = Prefs.shared
        let oldSync = prefs.syncNotesSidecar
        defer { prefs.syncNotesSidecar = oldSync }
        prefs.syncNotesSidecar = true

        let annotator = Annotator(opensToRead: true)
        let view = try attach(annotator, to: pdf)
        defer { annotator.detach(); _ = view }
        let text = try await waitForText(at: notesSidecarURL(for: pdf), containing: "from Preview")
        XCTAssertTrue(text.contains("Generated by PaperShelf"), text)
    }

    /// Shown in passing, the same paper is left without a new file beside it; a notes file
    /// it already has is brought up to date all the same.
    func testAPaperShownInPassingOnlyRefreshesANotesFileItHas() async throws {
        let (folder, pdf) = try paperMarkedElsewhere()
        defer { try? FileManager.default.removeItem(at: folder) }
        let prefs = Prefs.shared
        let oldSync = prefs.syncNotesSidecar
        defer { prefs.syncNotesSidecar = oldSync }
        prefs.syncNotesSidecar = true
        let sidecar = notesSidecarURL(for: pdf)

        let passing = Annotator()
        let view = try attach(passing, to: pdf)
        for _ in 0..<100 where passing.marks.isEmpty {
            try await Task.sleep(for: .milliseconds(10))
        }
        XCTAssertEqual(passing.marks.count, 1, "the marks were never read")
        await passing.finishSaving()
        XCTAssertFalse(FileManager.default.fileExists(atPath: sidecar.path),
                       "a paper shown in passing was given a notes file")
        passing.detach()

        try Data("stale".utf8).write(to: sidecar)
        try FileManager.default.setAttributes([.modificationDate: Date().addingTimeInterval(-3600)],
                                              ofItemAtPath: sidecar.path)
        let again = Annotator()
        again.attach(view, url: pdf)
        defer { again.detach() }
        let text = try await waitForText(at: sidecar, containing: "from Preview")
        XCTAssertFalse(text.contains("stale"), "the notes file it had was left out of date")
    }

    private func waitForText(at url: URL, containing needle: String) async throws -> String {
        for _ in 0..<50 {
            if let text = try? String(contentsOf: url), text.contains(needle) { return text }
            try await Task.sleep(for: .milliseconds(20))
        }
        return try String(contentsOf: url)
    }
}
